-- Row count check
SELECT COUNT(*) FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS;

-- Duplicate check
SELECT CUSTOMER_ID, COUNT(*) 
FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS
GROUP BY CUSTOMER_ID HAVING COUNT(*) > 1;

-- Null check on TOTAL_CHARGES
SELECT COUNT(*) FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS WHERE TOTAL_CHARGES IS NULL;

-- Invalid Churn values
SELECT CHURN, COUNT(*) FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS GROUP BY CHURN;

