-- High-risk customers
SELECT *
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS
WHERE RISK_LEVEL = 'HIGH'
ORDER BY CHURN_PROBABILITY DESC;

-- Risk distribution
SELECT RISK_LEVEL, COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS
GROUP BY RISK_LEVEL;

-- Average churn probability
SELECT AVG(CHURN_PROBABILITY) AS AVG_PROBABILITY
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS;

-- High-risk customers by contract
SELECT f.CONTRACT, COUNT(*) AS HIGH_RISK_COUNT
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS p
JOIN CUSTOMER_ANALYTICS.MART.FACT_CUSTOMER_BILLING f ON p.CUSTOMER_ID = f.CUSTOMER_ID
WHERE p.RISK_LEVEL = 'HIGH'
GROUP BY f.CONTRACT;

-- High-risk customers by payment method
SELECT f.PAYMENT_METHOD, COUNT(*) AS HIGH_RISK_COUNT
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS p
JOIN CUSTOMER_ANALYTICS.MART.FACT_CUSTOMER_BILLING f ON p.CUSTOMER_ID = f.CUSTOMER_ID
WHERE p.RISK_LEVEL = 'HIGH'
GROUP BY f.PAYMENT_METHOD;

-- High-risk customers by internet service
SELECT s.INTERNET_SERVICE, COUNT(*) AS HIGH_RISK_COUNT
FROM CUSTOMER_ANALYTICS.ML.CHURN_PREDICTIONS p
JOIN CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS s ON p.CUSTOMER_ID = s.CUSTOMER_ID
WHERE p.RISK_LEVEL = 'HIGH'
GROUP BY s.INTERNET_SERVICE;

