USE SCHEMA STAGING;

CREATE OR REPLACE TABLE TELCO_CUSTOMERS AS
SELECT
    CUSTOMERID AS CUSTOMER_ID,
    GENDER,
    CAST(SENIORCITIZEN AS INT) AS SENIOR_CITIZEN,
    PARTNER,
    DEPENDENTS,
    CAST(TENURE AS INT) AS TENURE,
    PHONESERVICE AS PHONE_SERVICE,
    MULTIPLELINES AS MULTIPLE_LINES,
    INTERNETSERVICE AS INTERNET_SERVICE,
    ONLINESECURITY AS ONLINE_SECURITY,
    ONLINEBACKUP AS ONLINE_BACKUP,
    DEVICEPROTECTION AS DEVICE_PROTECTION,
    TECHSUPPORT AS TECH_SUPPORT,
    STREAMINGTV AS STREAMING_TV,
    STREAMINGMOVIES AS STREAMING_MOVIES,
    CONTRACT,
    PAPERLESSBILLING AS PAPERLESS_BILLING,
    PAYMENTMETHOD AS PAYMENT_METHOD,
    CAST(MONTHLYCHARGES AS FLOAT) AS MONTHLY_CHARGES,
    TRY_CAST(NULLIF(TRIM(TOTALCHARGES), '') AS FLOAT) AS TOTAL_CHARGES,
    CHURN
FROM CUSTOMER_ANALYTICS.RAW.TELCO_CUSTOMERS;

