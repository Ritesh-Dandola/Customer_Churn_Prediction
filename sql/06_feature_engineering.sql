USE SCHEMA ML;

CREATE OR REPLACE VIEW CHURN_FEATURES AS
SELECT
    C.CUSTOMER_ID,
    C.GENDER,
    C.SENIOR_CITIZEN,
    C.PARTNER,
    C.DEPENDENTS,
    B.TENURE,
    B.MONTHLY_CHARGES,
    B.TOTAL_CHARGES,
    B.CONTRACT,
    B.PAYMENT_METHOD,
    B.PAPERLESS_BILLING,
    S.PHONE_SERVICE,
    S.MULTIPLE_LINES,
    S.INTERNET_SERVICE,
    S.ONLINE_SECURITY,
    S.ONLINE_BACKUP,
    S.DEVICE_PROTECTION,
    S.TECH_SUPPORT,
    S.STREAMING_TV,
    S.STREAMING_MOVIES,
    
    -- Feature Engineering
    CASE 
        WHEN B.TENURE <= 12 THEN '0-1 Year'
        WHEN B.TENURE <= 24 THEN '1-2 Years'
        WHEN B.TENURE <= 48 THEN '2-4 Years'
        ELSE '4+ Years' 
    END AS TENURE_GROUP,
    
    IFF(S.ONLINE_SECURITY = 'Yes', 1, 0) AS HAS_ONLINE_SECURITY,
    IFF(S.ONLINE_BACKUP = 'Yes', 1, 0) AS HAS_ONLINE_BACKUP,
    IFF(S.DEVICE_PROTECTION = 'Yes', 1, 0) AS HAS_DEVICE_PROTECTION,
    IFF(S.TECH_SUPPORT = 'Yes', 1, 0) AS HAS_TECH_SUPPORT,
    IFF(B.CONTRACT = 'Month-to-month', 1, 0) AS IS_MONTH_TO_MONTH,
    IFF(B.PAYMENT_METHOD IN ('Electronic check', 'Credit card (automatic)'), 1, 0) AS IS_ELECTRONIC_PAYMENT,
    
    -- Count of services
    (IFF(S.PHONE_SERVICE = 'Yes', 1, 0) + 
     IFF(S.INTERNET_SERVICE != 'No', 1, 0) +
     IFF(S.ONLINE_SECURITY = 'Yes', 1, 0) +
     IFF(S.ONLINE_BACKUP = 'Yes', 1, 0) +
     IFF(S.DEVICE_PROTECTION = 'Yes', 1, 0) +
     IFF(S.TECH_SUPPORT = 'Yes', 1, 0) +
     IFF(S.STREAMING_TV = 'Yes', 1, 0) +
     IFF(S.STREAMING_MOVIES = 'Yes', 1, 0)) AS NUMBER_OF_SERVICES,
     
    B.CHURN
FROM CUSTOMER_ANALYTICS.MART.DIM_CUSTOMER C
JOIN CUSTOMER_ANALYTICS.MART.FACT_CUSTOMER_BILLING B ON C.CUSTOMER_ID = B.CUSTOMER_ID
JOIN CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS S ON C.CUSTOMER_ID = S.CUSTOMER_ID;

