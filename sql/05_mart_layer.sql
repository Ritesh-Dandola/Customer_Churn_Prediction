USE SCHEMA MART;

CREATE OR REPLACE TABLE DIM_CUSTOMER AS
SELECT CUSTOMER_ID, GENDER, SENIOR_CITIZEN, PARTNER, DEPENDENTS
FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS;

CREATE OR REPLACE TABLE DIM_CONTRACT AS
SELECT DISTINCT CONTRACT FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS;

CREATE OR REPLACE TABLE DIM_PAYMENT_METHOD AS
SELECT DISTINCT PAYMENT_METHOD FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS;

CREATE OR REPLACE TABLE FACT_CUSTOMER_BILLING AS
SELECT 
    CUSTOMER_ID,
    TENURE,
    MONTHLY_CHARGES,
    TOTAL_CHARGES,
    CONTRACT,
    PAYMENT_METHOD,
    PAPERLESS_BILLING,
    CHURN
FROM CUSTOMER_ANALYTICS.STAGING.TELCO_CUSTOMERS;

